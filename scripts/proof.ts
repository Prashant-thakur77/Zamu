/**
 * Every number in PROOF.md, the README and SUBMISSION.md comes from here.
 *
 *   DATABASE_URL=... npx tsx scripts/proof.ts            # print + write PROOF.md
 *   DATABASE_URL=... npx tsx scripts/proof.ts --method mpesa
 *
 * Tap → delivered is measured from the moment the member tapped Pay (invoice
 * issued) to the moment the payout partner reported the M-Pesa receipt.
 * Payout-leg cost is the Lightning amount paid above the partner's published
 * shilling rate for that round: sats×1000 ÷ (KES × msats-per-KES) − 1.
 */
import { writeFileSync } from 'node:fs'
import { asc, eq } from 'drizzle-orm'
import { closeDb, getDb, schema } from '../db'

const method = (process.argv.includes('--method') ? process.argv[process.argv.indexOf('--method') + 1] : 'mpesa') as 'mpesa' | 'lightning' | 'nim'

function median(xs: number[]): number | null {
  if (xs.length === 0) return null
  const s = [...xs].sort((a, b) => a - b)
  const m = Math.floor(s.length / 2)
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2
}

const fmt = (n: number | null, d = 1) => (n === null ? '–' : n.toFixed(d))

async function main() {
  const rows = await getDb()
    .select({ inv: schema.invoices, rate: schema.rounds.msatsPerKes })
    .from(schema.invoices)
    .innerJoin(schema.rounds, eq(schema.rounds.id, schema.invoices.roundId))
    .where(eq(schema.invoices.method, method))
    .orderBy(asc(schema.invoices.tappedAt))

  const paid = rows.filter((r) => r.inv.nimiqHash)
  const delivered = paid.filter((r) => r.inv.status === 'delivered' && r.inv.deliveredAt)
  const failed = paid.filter((r) => r.inv.status === 'failed')
  const pending = paid.filter((r) => ['submitted', 'checking'].includes(r.inv.status))

  const tapToDelivered = delivered.map((r) => (r.inv.deliveredAt!.getTime() - r.inv.tappedAt.getTime()) / 1000)
  const submitToDelivered = delivered
    .filter((r) => r.inv.submittedAt)
    .map((r) => (r.inv.deliveredAt!.getTime() - r.inv.submittedAt!.getTime()) / 1000)
  const costs = delivered
    .filter((r) => r.inv.msats && r.rate)
    .map((r) => (Number(r.inv.msats) / (r.inv.kes * Number(r.rate)) - 1) * 100)
  const kes = delivered.reduce((a, r) => a + (r.inv.kesDelivered ?? r.inv.kes), 0)

  const table = [
    '| Measure | Value |',
    '| --- | --- |',
    `| Payouts delivered (${method}) | ${delivered.length} |`,
    `| Median seconds, tap → M-Pesa | ${fmt(median(tapToDelivered))} |`,
    `| Worst seconds, tap → M-Pesa | ${fmt(tapToDelivered.length ? Math.max(...tapToDelivered) : null)} |`,
    `| Median seconds, Nimiq Pay submit → M-Pesa | ${fmt(median(submitToDelivered))} |`,
    `| Total delivered | KSh ${kes.toLocaleString('en-US')} |`,
    `| Payout-leg cost (median, vs partner rate) | ${costs.length ? fmt(median(costs), 2) + '%' : '–'} |`,
    `| Payout-leg cost (range) | ${costs.length ? `${fmt(Math.min(...costs), 2)}% – ${fmt(Math.max(...costs), 2)}%` : '–'} |`,
    `| Failed | ${failed.length} |`,
    `| Still pending | ${pending.length} |`,
  ].join('\n')

  const detail = [
    '| # | KES | sats | Tap → delivered (s) | M-Pesa receipt | Nimiq tx | Swap | Payment hash |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...delivered.map((r, i) => {
      const s = (r.inv.deliveredAt!.getTime() - r.inv.tappedAt.getTime()) / 1000
      return `| ${i + 1} | ${r.inv.kes} | ${r.inv.sats ?? '–'} | ${s.toFixed(1)} | ${r.inv.receiptCode ?? '–'} | \`${(r.inv.nimiqHash ?? '').slice(0, 12)}…\` | ${r.inv.swapId ?? '–'} | \`${(r.inv.paymentHash ?? '').slice(0, 12)}…\` |`
    }),
  ].join('\n')

  const md = `# Proof

Generated by \`scripts/proof.ts\` from the production database on ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC.

${table}

## Every delivered payout

${delivered.length ? detail : '_No delivered payouts yet._'}

Cost is the Lightning amount paid over the payout partner's published KES rate for that round. It excludes the Nimiq Pay swap from NIM/USDT to Lightning, which the wallet shows the member before they confirm.
`
  console.log(md)
  writeFileSync('PROOF.md', md)
  await closeDb()
}

main().catch(async (e) => {
  console.error(e)
  await closeDb()
  process.exit(1)
})
