import { expect, test } from '@playwright/test'
import { activeChama, createChama, joinChama, phone, signIn, user } from './helpers'

test('pot planner: sliders update the pot and prefill the start form', async ({ browser }) => {
  const page = await user(browser)
  await page.goto('/')
  const planner = page.getByTestId('planner')
  await expect(page.getByTestId('plan-turn')).toContainText('As number')
  await planner.getByRole('slider', { name: 'Members' }).fill('10')
  await expect(page.getByTestId('plan-members')).toHaveText('10')
  await planner.getByRole('radio', { name: '2,000' }).click()
  await expect(planner).toContainText('18,000')
  await planner.getByRole('radio', { name: 'every month' }).click()
  await expect(planner).toContainText('10 months')
  await planner.getByRole('slider', { name: 'Your place in the order' }).fill('4')
  await expect(page.getByTestId('plan-turn')).toContainText('As number 4')
  await page.getByTestId('plan-start').click()
  await expect(page).toHaveURL(/\/start\?share=2000&size=10&freq=monthly/)
  await signIn(page)
  await page.goto('/start?share=2000&size=10&freq=monthly')
  await expect(page.getByTestId('share')).toHaveValue('2000')
  await expect(page.getByTestId('size')).toHaveText('10')
  await expect(page.getByRole('radio', { name: 'every month' })).toHaveAttribute('aria-checked', 'true')
})

test('tab bar reaches every section, help answers open and close', async ({ browser }) => {
  const page = await user(browser)
  await page.goto('/')
  await page.getByTestId('tab-help').click()
  await expect(page).toHaveURL(/\/help/)
  await expect(page.getByTestId('faq')).toContainText('Who holds the money?')
  await page.getByRole('button', { name: 'Who holds the money?' }).click()
  await expect(page.getByText(/Zamu never holds funds/)).toBeVisible()
  await page.getByTestId('tab-me').click()
  await expect(page).toHaveURL(/\/me/)
  await page.getByTestId('tab-ring').click()
  await expect(page).toHaveURL(/\/chamas/)
  await page.getByTestId('tab-home').click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('M-Pesa')
})

test('invite QR and copy link; change payout and leave while forming', async ({ browser }) => {
  const a = await user(browser)
  const b = await user(browser)
  await signIn(a)
  await signIn(b)
  const { url, code } = await createChama(a, { name: 'QR test', share: 100, size: 4, you: 'Wanjiru', phone: phone() })
  await a.getByTestId('show-qr').click()
  await expect(a.getByTestId('qr').locator('svg')).toBeVisible()
  await expect(a.getByText(`/join?code=${code}`)).toBeVisible()

  await joinChama(b, code, 'Otieno', phone())
  await b.getByTestId('change-payout').click()
  await b.getByTestId('payout-lightning').click()
  await b.getByTestId('lightning').fill('otieno@wallet.example')
  await b.getByTestId('consent').check()
  await b.getByTestId('save-payout').click()
  await expect(b.getByText('Saved.')).toBeVisible()
  await expect(b.getByTestId('members')).toContainText('Lightning')
  await b.getByTestId('leave').click()
  await b.getByTestId('leave-yes').click()
  await expect(b).toHaveURL(/\/chamas/)
  await a.goto(url)
  await expect(a.getByTestId('members').locator('li')).toHaveCount(1)
})

test('receipts, activity and my record after a delivered share', async ({ browser }) => {
  const { a, b, url } = await activeChama(browser, phone('678'))
  await b.goto(url)
  await b.getByTestId('open-pay').click()
  await b.getByTestId('pay').click()
  await expect(b.getByTestId('delivered')).toBeVisible({ timeout: 30_000 })
  await b.getByRole('button', { name: 'Close' }).click()

  await b.getByTestId('tab-receipts').click()
  await expect(b.getByTestId('receipts')).toContainText('1 receipt ·')
  await expect(b.getByTestId('receipts')).toContainText('M-PESA')
  await b.getByTestId('tab-activity').click()
  await expect(b.getByTestId('activity')).toContainText("Otieno's share reached Wanjiru")
  await expect(b.getByTestId('activity')).toContainText('Wanjiru started the chama')

  await b.goto('/me')
  await expect(b.getByTestId('me')).toContainText('KSh')
  await expect(b.getByTestId('reliability')).toHaveText('100%')

  await a.goto('/me')
  await expect(a.getByTestId('me-turns')).toContainText('Collecting now')
  await expect(a.getByTestId('me')).toContainText('100')
})
