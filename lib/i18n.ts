export type Key = keyof (typeof dict)['en']

export function translate(lang: 'en' | 'sw', key: Key, vars?: Record<string, string | number>): string {
  let s: string = dict[lang][key] ?? dict.en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export function formatKes(n: number): string {
  return `KSh ${Math.round(n).toLocaleString('en-US')}`
}

export function formatDay(iso: string | Date, lang: 'en' | 'sw'): string {
  const d = new Date(iso)
  return d.toLocaleDateString(lang === 'sw' ? 'sw-KE' : 'en-GB', { weekday: 'short', day: 'numeric', month: 'short' })
}
